from __future__ import annotations

from datetime import datetime
from typing import Protocol, runtime_checkable, Sequence
from .models import Seat, Reservation


@runtime_checkable
class SeatRepository(Protocol):
    def list_all_ordered(self) -> Sequence[Seat]: ...
    def get_by_id_for_update(self, seat_id: int) -> Seat | None: ...
    def count(self) -> int: ...
    def add_many(self, seats: Sequence[Seat]) -> None: ...


@runtime_checkable
class ReservationRepository(Protocol):
    def get_active_for_seat(self, seat_id: int, for_update: bool = False) -> Reservation | None: ...
    def get_by_id_for_update(self, reservation_id: int) -> Reservation | None: ...
    def add(self, reservation: Reservation) -> None: ...


@runtime_checkable
class ExpirationPolicy(Protocol):
    def is_expired(self, reservation: Reservation, now: datetime) -> bool: ...
    def expires_at(self, now: datetime) -> datetime: ...
    def expire_if_needed(self, reservation: Reservation, now: datetime) -> bool: ...